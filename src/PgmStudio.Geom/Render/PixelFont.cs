namespace PgmStudio.Geom.Render;

/// <summary>
/// A minimal 5×5 bitmap font — capital letters, digits and the handful of symbols a render's legend or scale
/// bar needs to spell out a word or a number. Nothing here reads a system font: a render is a self-contained
/// pixel buffer with no font file to ship or license, and a legend only ever needs a short, fixed vocabulary
/// (a role name, a category name, a count of blocks), which a hand-drawn glyph set covers without the weight
/// of a real typeface.
/// </summary>
public static class PixelFont
{
