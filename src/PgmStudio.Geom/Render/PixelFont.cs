    /// <summary>The 5×5 glyph for a character, upper-cased first. An unknown character reads as a blank cell
    /// rather than throwing, so a caller need not pre-validate a label before drawing it.</summary>
    public static string[] Glyph(char character) =>
        Glyphs.TryGetValue(char.ToUpperInvariant(character), out var rows) ? rows : Glyphs[' '];
}
