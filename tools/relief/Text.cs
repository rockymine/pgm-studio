    public static int Measure(string text) => text.Length * (GlyphWidth + 1);

    public static void Draw(Canvas canvas, string text, int x, int y, int rgb)
    {
        var cursor = x;
        foreach (var raw in text)
        {
            var glyph = Glyphs.GetValueOrDefault(char.ToUpperInvariant(raw));
            if (glyph is not null)
                for (var column = 0; column < GlyphWidth; column++)
                    for (var row = 0; row < GlyphHeight; row++)
                        if ((glyph[column] & (1 << row)) != 0) canvas.Set(cursor + column, y + row, rgb);
            cursor += GlyphWidth + 1;
        }
    }
}
